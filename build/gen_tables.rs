//! `gen-tables` — regenerate build/entities.rs and the tables in build/unicode.rs.
//!
//! The build has no dependencies, so the HTML5 entity list and the Unicode
//! character classes it needs are checked in as generated data. This tool
//! derives them from the published sources, which `make tables` downloads:
//!
//! - `entities.json` — the WHATWG list of named character references
//! - `UnicodeData.txt` — general categories (Unicode Character Database)
//! - `DerivedNumericType.txt` — numeric code points, Unihan numerals included
//!
//! Usage: `gen-tables DATA_DIR UNICODE_VERSION`. It replaced the Python
//! script that read the same data out of Python's standard library
//! (docs/adr/2026-10-11-rust-only-toolchain.md); the tables are byte-identical.

use std::fs;
use std::path::Path;
use std::process::ExitCode;

use posse_bliki_build::json::{self, Json};

const WIDTH: usize = 100;
const MAX_CP: u32 = 0x10ffff;

fn rust_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        if (' '..='~').contains(&c) && c != '"' && c != '\\' {
            out.push(c);
        } else {
            out.push_str(&format!("\\u{{{:x}}}", c as u32));
        }
    }
    out.push('"');
    out
}

fn ranges(pred: impl Fn(u32) -> bool) -> Vec<(u32, u32)> {
    let mut out = Vec::new();
    let mut start = None;
    for cp in 0..=MAX_CP + 1 {
        let hit = cp <= MAX_CP && pred(cp);
        match (hit, start) {
            (true, None) => start = Some(cp),
            (false, Some(s)) => {
                out.push((s, cp - 1));
                start = None;
            }
            _ => {}
        }
    }
    out
}

fn wrap(items: &[String]) -> String {
    let mut lines = Vec::new();
    let mut line = String::from("   ");
    for item in items {
        if line.len() + 1 + item.len() > WIDTH {
            lines.push(line);
            line = String::from("   ");
        }
        line.push(' ');
        line.push_str(item);
    }
    lines.push(line);
    lines.join("\n")
}

fn table(name: &str, doc: &str, pred: impl Fn(u32) -> bool) -> String {
    let items: Vec<String> = ranges(pred)
        .iter()
        .map(|(a, b)| format!("(0x{a:x}, 0x{b:x}),"))
        .collect();
    format!("/// {doc}\nstatic {name}: &[(u32, u32)] = &[\n{}\n];\n", wrap(&items))
}

fn entities(data: &Path) -> Result<String, String> {
    let text = fs::read_to_string(data.join("entities.json")).map_err(|e| format!("entities.json: {e}"))?;
    let Json::Obj(items) = json::parse(&text)? else {
        return Err("entities.json is not an object".into());
    };
    let mut names: Vec<(String, String)> = items
        .iter()
        .filter(|(k, _)| k.ends_with(';'))
        .map(|(k, v)| {
            let name = k.trim_start_matches('&').trim_end_matches(';').to_string();
            (name, v.str_at("characters").unwrap_or_default().to_string())
        })
        .collect();
    names.sort();
    names.dedup();
    let rows: Vec<String> = names
        .iter()
        .map(|(n, c)| format!("    ({}, {}),", rust_str(n), rust_str(c)))
        .collect();
    Ok(format!(
        "//! HTML5 named character references (generated by `make tables` from the WHATWG\n\
         //! entities.json; names have the trailing ';' stripped, as markdown-it-py does). Sorted for binary search.\n\
         \n\
         pub static ENTITIES: &[(&str, &str)] = &[\n\
         {}\n\
         ];\n\
         \n\
         pub fn lookup(name: &str) -> Option<&'static str> {{\n    \
         ENTITIES.binary_search_by(|(k, _)| (*k).cmp(name)).ok().map(|i| ENTITIES[i].1)\n\
         }}\n",
        rows.join("\n")
    ))
}

/// General category of every code point (`Cn` where unassigned).
fn categories(data: &Path) -> Result<Vec<[u8; 2]>, String> {
    let text = fs::read_to_string(data.join("UnicodeData.txt")).map_err(|e| format!("UnicodeData.txt: {e}"))?;
    let mut cats = vec![*b"Cn"; MAX_CP as usize + 1];
    let mut range_start = None;
    for line in text.lines() {
        let f: Vec<&str> = line.split(';').collect();
        let cp = u32::from_str_radix(f[0], 16).map_err(|e| format!("{line}: {e}"))?;
        let cat: [u8; 2] = f[2]
            .as_bytes()
            .try_into()
            .map_err(|_| format!("{line}: bad category"))?;
        if f[1].ends_with(", First>") {
            range_start = Some(cp);
            continue;
        }
        let start = if f[1].ends_with(", Last>") {
            range_start.take().ok_or("Last without First")?
        } else {
            cp
        };
        for c in start..=cp {
            cats[c as usize] = cat;
        }
    }
    Ok(cats)
}

/// Code points with a numeric type (Python's `str.isnumeric`).
fn numeric(data: &Path) -> Result<Vec<bool>, String> {
    let path = data.join("DerivedNumericType.txt");
    let text = fs::read_to_string(&path).map_err(|e| format!("DerivedNumericType.txt: {e}"))?;
    let mut out = vec![false; MAX_CP as usize + 1];
    for line in text.lines() {
        let line = line.split('#').next().unwrap().trim();
        if line.is_empty() {
            continue;
        }
        let (cps, kind) = line.split_once(';').ok_or(format!("bad line {line}"))?;
        if kind.trim() == "None" {
            continue;
        }
        let (lo, hi) = cps.trim().split_once("..").unwrap_or((cps.trim(), cps.trim()));
        let parse = |s: &str| u32::from_str_radix(s, 16).map_err(|e| format!("{line}: {e}"));
        for c in parse(lo)?..=parse(hi)? {
            out[c as usize] = true;
        }
    }
    Ok(out)
}

fn unicode_tables(data: &Path, version: &str) -> Result<String, String> {
    let cats = categories(data)?;
    let num = numeric(data)?;
    let header = format!(
        "//! Unicode property tables (generated by `make tables` from Unicode {version}) so that\n\
         //! character classes match the reference implementation exactly.\n\n"
    );
    let punct = table(
        "PUNCT_OR_SYMBOL",
        "General category P* or S* (markdown-it `isPunctChar`).",
        |cp| matches!(cats[cp as usize][0], b'P' | b'S'),
    );
    // Python's str.isalnum: a letter (L*) or a numeric character.
    let word = table("WORD", "Python `re` word characters: `str.isalnum()` or `_`.", |cp| {
        cats[cp as usize][0] == b'L' || num[cp as usize] || cp == '_' as u32
    });
    Ok(format!("{header}{punct}\n{word}"))
}

fn run(data: &Path, version: &str) -> Result<(), String> {
    let build = Path::new(env!("CARGO_MANIFEST_DIR")).join("build");
    fs::write(build.join("entities.rs"), entities(data)?).map_err(|e| e.to_string())?;
    let path = build.join("unicode.rs");
    let text = fs::read_to_string(&path).map_err(|e| e.to_string())?;
    let tail = &text[text.find("\nfn in_table").ok_or("unicode.rs has no `fn in_table`")?..];
    fs::write(&path, unicode_tables(data, version)? + tail).map_err(|e| e.to_string())
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [data, version] = args.as_slice() else {
        eprintln!("usage: gen-tables DATA_DIR UNICODE_VERSION");
        return ExitCode::from(2);
    };
    match run(Path::new(data), version) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-tables: {e}");
            ExitCode::FAILURE
        }
    }
}
